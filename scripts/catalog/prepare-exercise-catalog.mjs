#!/usr/bin/env node
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { buildCatalogSnapshot, SOURCE_CHECK_EVIDENCE } from './catalog-source.mjs';
import {
  buildCoverageMatrix,
  checksumForRaw,
  normalizeSearchV1,
  validateCatalog,
} from './catalog-validation.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const CATALOG_DIR = `${ROOT}assets/catalog`;
const PATHS = {
  json: `${CATALOG_DIR}/exercise-catalog-v1.json`,
  checksum: `${CATALOG_DIR}/exercise-catalog-v1.sha256`,
  generatedTs: `${CATALOG_DIR}/exercise-catalog-v1.generated.ts`,
  evidence: `${CATALOG_DIR}/exercise-catalog-v1.evidence.json`,
  coverage: `${CATALOG_DIR}/exercise-catalog-v1.coverage.json`,
  d1Sql: `${CATALOG_DIR}/exercise-catalog-v1.d1.sql`,
  schema: `${ROOT}docs/contracts/exercise-catalog-v1.schema.json`,
  compatibility: `${ROOT}docs/contracts/exercise-catalog-v1-compatibility.json`,
  seed: `${ROOT}src/db/seed.ts`,
};

const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  return sqlString(value);
};

function buildD1DraftSql(snapshot, raw, checksum) {
  const version = snapshot.catalogVersion;
  const checksumHex = checksum.slice('sha256:'.length);
  const effectiveAtMs = Date.parse(snapshot.effectiveAt);
  const lines = [
    '-- Generated by scripts/catalog/prepare-exercise-catalog.mjs.',
    '-- Publisher-prep only: inserts an immutable draft and never updates catalog_channel.',
    'BEGIN IMMEDIATE;',
    `INSERT INTO catalog_release (version, schema_version, effective_at_ms, checksum_hex, item_count, payload_bytes, payload_json, state, created_at_ms, published_at_ms) VALUES (${sqlString(version)}, ${sqlString(snapshot.schemaVersion)}, ${effectiveAtMs}, ${sqlString(checksumHex)}, ${snapshot.exercises.length}, ${raw.byteLength}, X'${raw.toString('hex')}', 'draft', ${effectiveAtMs}, NULL);`,
  ];

  for (const exercise of snapshot.exercises) {
    const target = exercise.defaultPrescription.target;
    lines.push(
      `INSERT INTO catalog_exercise (version, id, record_revision, status, effective_from_ms, effective_to_ms, replacement_id, display_order, exercise_type, is_bodyweight, movement_pattern, difficulty, default_sets, tracking_mode, target_unit, target_low, target_high, provenance_classification, review_status, review_method, reviewed_by_role, review_evidence, reviewed_at_ms, contains_third_party_copy) VALUES (${[
        version,
        exercise.id,
        exercise.recordRevision,
        exercise.status,
        Date.parse(exercise.effectiveFrom),
        exercise.effectiveTo === null ? null : Date.parse(exercise.effectiveTo),
        exercise.replacementId,
        exercise.displayOrder,
        exercise.exerciseType,
        exercise.isBodyweight ? 1 : 0,
        exercise.movementPattern,
        exercise.difficulty,
        exercise.defaultPrescription.sets,
        exercise.defaultPrescription.trackingMode,
        target?.unit,
        target?.low,
        target?.high,
        exercise.provenance.classification,
        exercise.provenance.reviewStatus,
        exercise.provenance.reviewMethod,
        exercise.provenance.reviewedByRole,
        exercise.provenance.reviewEvidence,
        Date.parse(exercise.provenance.reviewedAt),
        0,
      ].map(sqlValue).join(', ')});`,
    );

    for (const locale of snapshot.supportedLocales) {
      const localization = exercise.localizations[locale];
      lines.push(
        `INSERT INTO catalog_localization (version, exercise_id, locale, display_name, normalized_display_name) VALUES (${[version, exercise.id, locale, localization.displayName, normalizeSearchV1(localization.displayName)].map(sqlValue).join(', ')});`,
      );
      localization.aliases.forEach((alias, aliasOrder) => {
        lines.push(
          `INSERT INTO catalog_alias (version, exercise_id, locale, alias_order, alias, normalized_alias) VALUES (${[version, exercise.id, locale, aliasOrder, alias, normalizeSearchV1(alias)].map(sqlValue).join(', ')});`,
        );
      });
    }

    for (const role of ['required', 'optional']) {
      exercise.equipment[role].forEach((equipmentId, equipmentOrder) => {
        lines.push(
          `INSERT INTO catalog_equipment (version, exercise_id, role, equipment_order, equipment_id) VALUES (${[version, exercise.id, role, equipmentOrder, equipmentId].map(sqlValue).join(', ')});`,
        );
      });
    }

    for (const role of ['primary', 'secondary']) {
      const regions = role === 'primary' ? exercise.primaryBodyRegions : exercise.secondaryBodyRegions;
      regions.forEach((regionId, regionOrder) => {
        lines.push(
          `INSERT INTO catalog_region (version, exercise_id, role, region_order, region_id) VALUES (${[version, exercise.id, role, regionOrder, regionId].map(sqlValue).join(', ')});`,
        );
      });
    }

    exercise.provenance.sources.forEach((source, sourceOrder) => {
      lines.push(
        `INSERT INTO catalog_source (version, exercise_id, source_order, source_type, label, url, license, accessed_at_ms) VALUES (${[
          version,
          exercise.id,
          sourceOrder,
          source.sourceType,
          source.label,
          source.url,
          source.license,
          source.accessedAt === null ? null : Date.parse(source.accessedAt),
        ].map(sqlValue).join(', ')});`,
      );
    });
  }

  lines.push('COMMIT;', '');
  return lines.join('\n');
}

function buildGeneratedTs(raw, checksum) {
  return [
    '/* Generated by scripts/catalog/prepare-exercise-catalog.mjs. Do not edit. */',
    `export const BUNDLED_CATALOG_RAW = ${JSON.stringify(raw.toString('utf8'))} as const;`,
    `export const BUNDLED_CATALOG_CHECKSUM = ${JSON.stringify(checksum)} as const;`,
    '',
  ].join('\n');
}

async function expectedArtifacts() {
  const [schema, compatibility, seedSource] = await Promise.all([
    readFile(PATHS.schema, 'utf8').then(JSON.parse),
    readFile(PATHS.compatibility, 'utf8').then(JSON.parse),
    readFile(PATHS.seed, 'utf8'),
  ]);
  const seedIds = [...seedSource.matchAll(/\bid:\s*'([^']+)'/g)].map((match) => match[1]);
  const snapshot = buildCatalogSnapshot();
  const raw = Buffer.from(JSON.stringify(snapshot), 'utf8');
  const checksum = checksumForRaw(raw);
  const sidecar = `${checksum}\n`;
  const result = validateCatalog({
    snapshot,
    schema,
    compatibility,
    evidence: SOURCE_CHECK_EVIDENCE,
    seedIds,
    raw,
    sidecar,
  });
  const coverage = buildCoverageMatrix(snapshot, schema);
  return {
    summary: {
      catalogVersion: snapshot.catalogVersion,
      exercises: snapshot.exercises.length,
      payloadBytes: result.payloadBytes,
      checksum,
      strength: coverage.exerciseTypes.strength.count,
      cardio: coverage.exerciseTypes.cardio.count,
    },
    files: new Map([
      [PATHS.json, raw],
      [PATHS.checksum, sidecar],
      [PATHS.generatedTs, buildGeneratedTs(raw, checksum)],
      [PATHS.evidence, `${JSON.stringify(SOURCE_CHECK_EVIDENCE, null, 2)}\n`],
      [PATHS.coverage, `${JSON.stringify(coverage, null, 2)}\n`],
      [PATHS.d1Sql, buildD1DraftSql(snapshot, raw, checksum)],
    ]),
  };
}

async function main() {
  const checkOnly = process.argv.includes('--check');
  const { files, summary } = await expectedArtifacts();
  if (checkOnly) {
    for (const [path, expected] of files) {
      let actual;
      try {
        actual = await readFile(path);
      } catch {
        throw new Error(`${path}: generated artifact is missing`);
      }
      const expectedBuffer = Buffer.isBuffer(expected) ? expected : Buffer.from(expected, 'utf8');
      if (!actual.equals(expectedBuffer)) {
        throw new Error(`${path}: generated artifact is stale; run npm run catalog:prepare`);
      }
    }
    console.log(JSON.stringify({ status: 'ok', mode: 'check', ...summary }));
    return;
  }

  await mkdir(CATALOG_DIR, { recursive: true });
  await Promise.all(
    [...files].map(([path, contents]) => writeFile(path, contents)),
  );
  console.log(JSON.stringify({ status: 'ok', mode: 'write', ...summary }));
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
